#!/bin/bash
# Installer for slurm-amlfs-flow.
# Run as root on the Slurm scheduler node.

set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PREFIX=/opt/slurm-amlfs-flow
VENV="$PREFIX/venv"
PKG_DIR="$PREFIX/amlfs_flow"
SLURM_ETC=/etc/slurm
STATE_DIR=/sched/slurm-amlfs-flow
SLURM_USER=slurm

# ── Args ───────────────────────────────────────────────────────────────
SUBSCRIPTION=""
AMLFS_PRIMARY_RG=""
AMLFS_PRIMARY_NAME=""
AMLFS_SECONDARY_RG=""
AMLFS_SECONDARY_NAME=""
PRIMARY_PARTITION="hpc"
SECONDARY_PARTITION="htc"
STAGEIN_CONFLICT_MODE="Skip"
STAGEOUT_CONFLICT_MODE="OverwriteAlways"

usage() {
    cat <<EOF
Usage: $0 --subscription <SUB_ID> \\
          --amlfs-primary-rg <RG_A> --amlfs-primary-name <FS_A> \\
          --amlfs-secondary-rg <RG_B> --amlfs-secondary-name <FS_B> \\
          [--primary-partition <name>]   (default: hpc)
          [--secondary-partition <name>]   (default: htc)
          [--stagein-conflict-mode <mode>]   (default: Skip)
          [--stageout-conflict-mode <mode>]  (default: OverwriteAlways)
          Conflict modes: Skip | Fail | OverwriteAlways | OverwriteIfDirty
EOF
    exit 1
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --subscription)        SUBSCRIPTION="$2"; shift 2 ;;
        --amlfs-primary-rg)          AMLFS_PRIMARY_RG="$2"; shift 2 ;;
        --amlfs-primary-name)        AMLFS_PRIMARY_NAME="$2"; shift 2 ;;
        --amlfs-secondary-rg)          AMLFS_SECONDARY_RG="$2"; shift 2 ;;
        --amlfs-secondary-name)        AMLFS_SECONDARY_NAME="$2"; shift 2 ;;
        --primary-partition)  PRIMARY_PARTITION="$2"; shift 2 ;;
        --secondary-partition)  SECONDARY_PARTITION="$2"; shift 2 ;;
        --stagein-conflict-mode)  STAGEIN_CONFLICT_MODE="$2"; shift 2 ;;
        --stageout-conflict-mode) STAGEOUT_CONFLICT_MODE="$2"; shift 2 ;;
        -h|--help) usage ;;
        *) echo "Unknown arg: $1"; usage ;;
    esac
done

for v in SUBSCRIPTION AMLFS_PRIMARY_RG AMLFS_PRIMARY_NAME AMLFS_SECONDARY_RG AMLFS_SECONDARY_NAME; do
    [[ -n "${!v}" ]] || { echo "Missing --${v,,}"; usage; }
done

VALID_MODES=(Skip Fail OverwriteAlways OverwriteIfDirty)
for v in STAGEIN_CONFLICT_MODE STAGEOUT_CONFLICT_MODE; do
    ok=0
    for m in "${VALID_MODES[@]}"; do [[ "${!v}" == "$m" ]] && ok=1; done
    [[ $ok -eq 1 ]] || { echo "ERROR: $v='${!v}' — must be one of: ${VALID_MODES[*]}"; exit 1; }
done

if [[ $EUID -ne 0 ]]; then
    echo "ERROR: must run as root"
    exit 1
fi

echo "==> Installing python venv at $VENV"
mkdir -p "$PREFIX"
if [[ ! -d "$VENV" ]]; then
    python3 -m venv "$VENV"
fi
"$VENV/bin/pip" install --quiet --upgrade pip
"$VENV/bin/pip" install --quiet -r "$REPO_DIR/requirements.txt"

echo "==> Installing python helper at $PKG_DIR"
mkdir -p "$PKG_DIR"
cp "$REPO_DIR/amlfs_flow/__init__.py" "$PKG_DIR/__init__.py"
cp "$REPO_DIR/amlfs_flow/__main__.py" "$PKG_DIR/__main__.py"

# Make the package importable from the venv via a .pth file
SITE_PACKAGES=$("$VENV/bin/python" -c "import sysconfig; print(sysconfig.get_paths()['purelib'])")
echo "$PREFIX" > "$SITE_PACKAGES/amlfs_flow.pth"

echo "==> Rendering amlfs_flow/config.py"
cat > "$PKG_DIR/config.py" <<EOF
"""Auto-generated by install.sh — DO NOT edit by hand."""

SUBSCRIPTION_ID = "$SUBSCRIPTION"

AMLFS_PRIMARY_RESOURCE_GROUP = "$AMLFS_PRIMARY_RG"
AMLFS_PRIMARY_NAME           = "$AMLFS_PRIMARY_NAME"
AMLFS_PRIMARY_MOUNT          = "/lustre"

AMLFS_SECONDARY_RESOURCE_GROUP = "$AMLFS_SECONDARY_RG"
AMLFS_SECONDARY_NAME           = "$AMLFS_SECONDARY_NAME"
AMLFS_SECONDARY_MOUNT          = "/lustre"

# Blob path = filesystem-relative path (shared HSM container)
BLOB_STAGE_PREFIX = ""

PRIMARY_PARTITION   = "$PRIMARY_PARTITION"
SECONDARY_PARTITION = "$SECONDARY_PARTITION"

STATE_DIR = "$STATE_DIR"

STAGEIN_CONFLICT_MODE  = "$STAGEIN_CONFLICT_MODE"
STAGEOUT_CONFLICT_MODE = "$STAGEOUT_CONFLICT_MODE"

ARCHIVE_POLL_INTERVAL = 15
IMPORT_POLL_INTERVAL  = 15
LRO_TIMEOUT           = 10800
EOF

echo "==> Installing Slurm BB hook to $SLURM_ETC"
# Template the primary partition name into the Lua hook so it can skip
# staging for jobs that don't need it.
sed "s|@PRIMARY_PARTITION@|$PRIMARY_PARTITION|g" \
    "$REPO_DIR/slurm/burst_buffer.lua" > "$SLURM_ETC/burst_buffer.lua"
cp "$REPO_DIR/slurm/burst_buffer.conf" "$SLURM_ETC/burst_buffer.conf"
chmod 644 "$SLURM_ETC/burst_buffer.lua" "$SLURM_ETC/burst_buffer.conf"

echo "==> Preparing state directory $STATE_DIR"
mkdir -p "$STATE_DIR"
chown "$SLURM_USER:$SLURM_USER" "$STATE_DIR"
chmod 0775 "$STATE_DIR"
# Pre-create lock files so flock(1) can open them as slurm user
for f in archive-stagein archive-stageout; do
    touch "$STATE_DIR/$f.lock"
    chown "$SLURM_USER:$SLURM_USER" "$STATE_DIR/$f.lock"
    chmod 0664 "$STATE_DIR/$f.lock"
done

echo "==> Preparing log directory"
mkdir -p /var/log/slurm
chown "$SLURM_USER:$SLURM_USER" /var/log/slurm
touch /var/log/slurm/amlfs_flow.log
chown "$SLURM_USER:$SLURM_USER" /var/log/slurm/amlfs_flow.log
chmod 0664 /var/log/slurm/amlfs_flow.log

echo ""
echo "Done. Next steps:"
echo "  1) Add to /etc/slurm/slurm.conf:"
echo "       BurstBufferType=burst_buffer/lua"
echo "       DebugFlags=BurstBuffer"
echo "  2) sudo scontrol reconfigure"
echo "  3) sudo $REPO_DIR/scripts/selftest.sh"
